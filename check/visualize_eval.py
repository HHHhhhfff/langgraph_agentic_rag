def render_stage(case: dict[str, Any], stage: str, top_n: int, max_text_chars: int, *, show_removed: bool) -> str:
    real_hits = case.get("stages", {}).get(stage)
    hits = (case.get("visual_stages", {}).get(stage) if show_removed else None) or real_hits
    if not isinstance(hits, list):
        hits = []
    if not isinstance(real_hits, list):
        real_hits = []
    expected_pages = case.get("expected_pages") if isinstance(case.get("expected_pages"), list) else []
    shown_hits = hits[:top_n] if top_n > 0 else hits
    summary = stage_summary(real_hits, expected_pages)
    removed_stats = removed_summary(hits)
    top1_class = "ok" if summary["top1"] else "bad"
    chunks_html = "".join(render_chunk(hit, expected_pages, max_text_chars, stage=stage) for hit in shown_hits)
    if not chunks_html:
        chunks_html = '<div class="empty-stage">No chunks recorded</div>'
    top_n_note = f"showing top {len(shown_hits)} of {len(hits)}" if top_n > 0 and len(hits) > top_n else f"{len(hits)} chunks"
    return f"""
    <section class="stage-column">
      <div class="stage-title">
        <h4>{esc(STAGE_LABELS.get(stage, stage))}</h4>
        <span class="{top1_class}">top1 {'hit' if summary['top1'] else 'miss'}</span>
      </div>
      <div class="stage-stats">
        <span>kept {summary['total']} | relevant {summary['relevant']}</span>
        <span>removed {removed_stats['removed']} | agent {removed_stats['agent']} | threshold {removed_stats['threshold']} | top-k {removed_stats['topk']} | inferred {removed_stats['inferred']}</span>
        <span>{esc(top_n_note)}</span>
      </div>
      {chunks_html}
    </section>
    """


def render_debug_panel(case: dict[str, Any]) -> str:
    debug = case.get("model_debug")
    if not isinstance(debug, dict):
        debug = {}
    fields = (
        "pipeline",
        "route",
        "executed_channels",
        "evidence_ok",
        "support_score",
        "support_level",
        "gate_decision",
        "gate_reasons",
        "missing_slots",
        "conflict_level",
        "conflict_reasons",
        "retry_count",
        "retry_actions",
        "agent_chunk_grading_used",
        "agent_chunk_grading_hit_count",
        "citation_ok",
        "rank_source",
        "page_tolerance",
    )
    rows = []
    for field in fields:
        value = debug.get(field)
        if value in (None, "", [], {}):
            continue
        rows.append(f"<tr><th>{esc(field)}</th><td>{esc(json.dumps(value, ensure_ascii=False) if isinstance(value, (list, dict)) else value)}</td></tr>")
    if not rows:
        return ""
    return f"""
    <section class="debug-section">
      <h3>TaskGraph / debug</h3>
      <table class="debug-table"><tbody>{''.join(rows)}</tbody></table>
    </section>
    """


def render_case(
    case: dict[str, Any],
    index: int,
    top_n: int,
    max_text_chars: int,
    stage_order: tuple[str, ...],
    *,
    show_removed: bool,
) -> str:
    metrics = case.get("metrics") if isinstance(case.get("metrics"), dict) else {}
    ai = case.get("ai_evaluation") if isinstance(case.get("ai_evaluation"), dict) else {}
