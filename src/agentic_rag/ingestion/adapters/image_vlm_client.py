class ImageVLMError(RuntimeError):
    """Raised when image VLM caption generation fails."""


@dataclass(slots=True)
class LocalImageReference:
    path: Path
    mime: str
    data_url: str
    file_uri: str
    size_bytes: int


SceneType = Literal["chart", "diagram", "screenshot", "photo", "document", "unknown"]


class ImageObjectDescription(BaseModel):
    """Single local object/region description from an image VLM."""

    label: str = ""
    description: str = ""
    confidence: float = 0.0


class ImageVLMDescription(BaseModel):
    """Structured image description generated by a VLM."""

    caption: str = ""
    scene_type: SceneType = "unknown"
    visible_text_summary: str = ""
    objects: list[ImageObjectDescription] = Field(default_factory=list)
    confidence: float = 0.0

    @field_validator("scene_type", mode="before")
    @classmethod
    def _normalize_scene_type(cls, value: object) -> str:
        if value is None:
            return "unknown"
        raw = str(value).strip()
        mapping = {
            "\u7f51\u9875\u622a\u56fe": "screenshot",
            "\u622a\u56fe": "screenshot",
            "\u56fe\u8868": "chart",
            "\u7167\u7247": "photo",
            "\u6587\u6863": "document",
            "chart": "chart",
            "diagram": "diagram",
            "screenshot": "screenshot",
            "photo": "photo",
            "document": "document",
            "unknown": "unknown",
        }
        return mapping.get(raw, mapping.get(raw.lower(), "unknown"))


class ImageVLMClient:
    """VLM client for image caption/object extraction."""

    MIME_MAP = {
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".jpe": "image/jpeg",
        ".png": "image/png",
        ".webp": "image/webp",
        ".bmp": "image/bmp",
        ".tif": "image/tiff",
        ".tiff": "image/tiff",
        ".heic": "image/heic",
    }
    FORMAT_MIME_MAP = {
        "JPEG": "image/jpeg",
        "PNG": "image/png",
        "WEBP": "image/webp",
        "BMP": "image/bmp",
        "TIFF": "image/tiff",
        "HEIC": "image/heic",
        "HEIF": "image/heic",
    }
    MAX_LOCAL_IMAGE_BYTES = 10 * 1024 * 1024
    MAX_BASE64_CHARS = 10 * 1024 * 1024

    def __init__(self, settings: Settings):
        self.settings = settings
        self.client = OpenAICompatibleClient(
            base_url=settings.image_vlm_base_url,
            api_key=settings.image_vlm_api_key,
            timeout=settings.image_vlm_timeout_sec,
        )

    def describe_image(self, image_path: str | Path) -> ImageVLMDescription:
        """Generate a structured semantic description for a local image."""

        retry_call = retry(
            reraise=True,
            stop=stop_after_attempt(self.settings.image_vlm_max_retries),
            wait=wait_exponential(multiplier=1, min=1, max=6),
            retry=retry_if_exception_type((ProviderError, ImageVLMError)),
        )(self._describe_once)
        return retry_call(Path(image_path))

    def _describe_once(self, image_path: Path) -> ImageVLMDescription:
        image_ref = self._prepare_local_image(image_path)
        if self.settings.image_vlm_provider == "dashscope_sdk":
            content = self._describe_dashscope(image_ref.file_uri)
            return self._parse_description(content)
        content = self._describe_openai_compatible(image_ref.data_url)
        return self._parse_description(content)

    def _describe_openai_compatible(self, data_url: str) -> str:
        payload: dict[str, Any] = {
            "model": self.settings.image_vlm_model,
            "stream": True,
            "enable_thinking": bool(self.settings.image_vlm_enable_thinking),
            "messages": [
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image_url",
                            "image_url": {"url": data_url},
                        },
                        {"type": "text", "text": self._prompt()},
                    ],
                }
            ],
        }
        if self.settings.image_vlm_enable_thinking:
            payload["thinking_budget"] = 81920
        chunks = self.client.post_stream("chat/completions", payload)
        return self._extract_openai_stream_content(chunks)

    def _describe_dashscope(self, image_ref: str) -> str:
        try:
            dashscope = importlib.import_module("dashscope")
        except ImportError as exc:
            raise ImageVLMError("dashscope package is required for IMAGE_VLM_PROVIDER=dashscope_sdk") from exc
        dashscope.base_http_api_url = self.settings.image_vlm_dashscope_api_url
        messages = [
            {
                "role": "user",
                "content": [
                    {"image": image_ref},
                    {"text": self._prompt()},
                ],
            }
        ]
        try:
            kwargs: dict[str, Any] = {
                "api_key": self.settings.image_vlm_api_key or os.getenv("DASHSCOPE_API_KEY"),
                "model": self.settings.image_vlm_model,
                "messages": messages,
                "stream": True,
                "enable_thinking": bool(self.settings.image_vlm_enable_thinking),
            }
            if self.settings.image_vlm_enable_thinking:
                kwargs["thinking_budget"] = 81920
            response = dashscope.MultiModalConversation.call(**kwargs)
        except Exception as exc:
            message = str(exc)
            if image_ref.startswith("data:"):
                message = f"DashScope SDK VLM rejected local data URL: {message}"
            elif image_ref.startswith("file:"):
                message = f"DashScope SDK VLM rejected local file URI: {message}"
            raise ImageVLMError(message) from exc
        return self._extract_dashscope_stream_or_content(response)

    def _parse_description(self, content: str) -> ImageVLMDescription:
        try:
            raw = extract_json_object(content)
            return ImageVLMDescription.model_validate(raw)
        except (JsonLLMError, ValidationError) as exc:
            raise ImageVLMError(f"Image VLM JSON validation failed: {exc}. raw_excerpt={self._safe_excerpt(content)}") from exc

    def _prompt(self) -> str:
        return (
            "你是图像理解模型。请只输出一个 JSON 对象，不要输出 Markdown，不要输出解释文本。\n"
            "JSON schema:\n"
            "{\n"
            '  "caption": "对图片内容的简洁描述",\n'
            '  "scene_type": "chart|diagram|screenshot|photo|document|unknown",\n'
            '  "visible_text_summary": "图片中可见文字/OCR 的摘要，没有则为空字符串",\n'
            '  "objects": [{"label": "对象名称", "description": "对象说明", "confidence": 0.0}],\n'
            '  "confidence": 0.0\n'
            "}\n"
            "要求：scene_type 必须使用英文枚举；网页截图用 screenshot；文档页面用 document；图表用 chart；"
            f"confidence 取 0 到 1；objects 最多返回 {self.settings.image_object_max_items} 个。"
        )

    def _prepare_local_image(self, image_path: Path) -> LocalImageReference:
        if not image_path.exists():
            raise ImageVLMError(f"Image file not found: {image_path}")
        try:
            content = image_path.read_bytes()
        except Exception as exc:
            raise ImageVLMError(f"Failed to read image file {image_path}: {exc}") from exc
        if not content:
            raise ImageVLMError(f"Image file is empty: {image_path}")
        mime = self._detect_image_mime(image_path, content)
        if len(content) > self.MAX_LOCAL_IMAGE_BYTES:
            raise ImageVLMError(
                f"Image file is too large for qwen3-vl-plus local input: {image_path} "
                f"size_bytes={len(content)} limit_bytes={self.MAX_LOCAL_IMAGE_BYTES}"
            )
        encoded = base64.b64encode(content).decode("utf-8")
        if len(encoded) > self.MAX_BASE64_CHARS:
            raise ImageVLMError(
                f"Image file is too large for qwen3-vl-plus base64 input: {image_path} "
                f"base64_chars={len(encoded)} limit_chars={self.MAX_BASE64_CHARS}"
            )
        return LocalImageReference(
            path=image_path,
            mime=mime,
            data_url=f"data:{mime};base64,{encoded}",
            file_uri=image_path.resolve().as_uri(),
            size_bytes=len(content),
        )

    @classmethod
    def _detect_image_mime(cls, image_path: Path, content: bytes) -> str:
        pil_mime = cls._detect_image_mime_with_pillow(image_path)
        magic_mime = cls._detect_image_mime_by_magic(content)
        mime = pil_mime or magic_mime
        if mime is None:
            header = content[:16].hex()
            raise ImageVLMError(
                f"Invalid or unsupported local image format for qwen3-vl-plus: {image_path} "
                f"suffix={image_path.suffix.lower() or '<none>'} header_hex={header}. "
                f"Supported local image MIME types: {', '.join(sorted(set(cls.MIME_MAP.values())))}"
            )
        return mime

    @classmethod
    def _detect_image_mime_with_pillow(cls, image_path: Path) -> str | None:
        try:
            from PIL import Image
        except ImportError:
            return None
        try:
            with Image.open(image_path) as image:
                image_format = str(image.format or "").upper()
                image.verify()
        except Exception as exc:
            raise ImageVLMError(f"Invalid or unreadable image file for qwen3-vl-plus: {image_path}: {exc}") from exc
        mime = cls.FORMAT_MIME_MAP.get(image_format)
        if mime is None:
            raise ImageVLMError(
                f"Unsupported local image format for qwen3-vl-plus: {image_path} "
                f"detected_format={image_format or '<unknown>'}. "
                f"Supported local image MIME types: {', '.join(sorted(set(cls.MIME_MAP.values())))}"
            )
        return mime

    @staticmethod
    def _detect_image_mime_by_magic(content: bytes) -> str | None:
        if content.startswith(b"\xff\xd8\xff"):
            return "image/jpeg"
        if content.startswith(b"\x89PNG\r\n\x1a\n"):
            return "image/png"
        if len(content) >= 12 and content[:4] == b"RIFF" and content[8:12] == b"WEBP":
            return "image/webp"
        if content.startswith(b"BM"):
            return "image/bmp"
        if content.startswith(b"II*\x00") or content.startswith(b"MM\x00*"):
            return "image/tiff"
        if len(content) >= 12 and content[4:8] == b"ftyp" and content[8:12] in {
            b"heic",
            b"heix",
            b"hevc",
            b"hevx",
            b"mif1",
            b"msf1",
        }:
            return "image/heic"
        return None

    @staticmethod
    def _extract_content(data: dict[str, Any]) -> str:
        choices = data.get("choices")
        if not isinstance(choices, list) or not choices:
            raise ImageVLMError("Image VLM response missing choices")
        message = choices[0].get("message") if isinstance(choices[0], dict) else None
        if not isinstance(message, dict):
            raise ImageVLMError("Image VLM response missing message")
        content = message.get("content")
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            return "\n".join(
                str(item.get("text") or item.get("content") or "")
                for item in content
                if isinstance(item, dict)
            )
        raise ImageVLMError("Image VLM response missing text content")

    @classmethod
    def _extract_openai_stream_content(cls, chunks: Any) -> str:
        answer_parts: list[str] = []
        for chunk in chunks:
            choices = chunk.get("choices") if isinstance(chunk, dict) else None
            if not isinstance(choices, list) or not choices:
                continue
            first = choices[0]
            if not isinstance(first, dict):
                continue
            delta = first.get("delta")
            if not isinstance(delta, dict):
                continue
            content = delta.get("content")
            if isinstance(content, str) and content:
                answer_parts.append(content)
            elif isinstance(content, list):
                answer_parts.extend(
                    str(item.get("text") or item.get("content") or "")
                    for item in content
                    if isinstance(item, dict)
                )
        text = "".join(answer_parts).strip()
        if text:
            return text
        raise ImageVLMError("Image VLM streaming response missing answer content")

    @staticmethod
    def _extract_dashscope_content(response: Any) -> str:
        content = _dig(response, ("output", "choices", 0, "message", "content"))
        if isinstance(content, list):
            text = "\n".join(str(item.get("text", "")) for item in content if isinstance(item, dict))
            if text.strip():
                return text
        if isinstance(content, str):
            return content
        if isinstance(response, dict):
            content = _dig(response, ("output", "choices", 0, "message", "content"))
            if isinstance(content, list):
                text = "\n".join(str(item.get("text", "")) for item in content if isinstance(item, dict))
                if text.strip():
                    return text
            if isinstance(content, str):
                return content
        raise ImageVLMError("DashScope VLM response missing text content")

    @classmethod
    def _extract_dashscope_stream_or_content(cls, response: Any) -> str:
        if isinstance(response, (dict, str)) or not hasattr(response, "__iter__"):
            return cls._extract_dashscope_content(response)
        answer_parts: list[str] = []
        try:
            for chunk in response:
                content = _dig(chunk, ("output", "choices", 0, "message", "content"))
                if isinstance(content, list):
                    answer_parts.extend(
                        str(item.get("text", ""))
                        for item in content
                        if isinstance(item, dict) and item.get("text")
                    )
                elif isinstance(content, str) and content:
                    answer_parts.append(content)
        except TypeError:
            return cls._extract_dashscope_content(response)
        text = "".join(answer_parts).strip()
        if text:
            return text
        raise ImageVLMError("DashScope VLM streaming response missing answer content")

    @staticmethod
    def _safe_excerpt(text: str, max_chars: int = 300) -> str:
        return " ".join((text or "").split())[:max_chars]


def image_vlm_description_to_json(description: ImageVLMDescription) -> str:
    """Return compact JSON for metadata/debug output."""

    return json.dumps(description.model_dump(), ensure_ascii=False, separators=(",", ":"))


def _dig(data: Any, path: tuple[Any, ...]) -> Any:
    current = data
    for key in path:
        if isinstance(key, int):
            if not isinstance(current, list) or key >= len(current):
                return None
            current = current[key]
        elif isinstance(current, dict):
            current = current.get(key)
        else:
            current = getattr(current, key, None)
        if current is None:
            return None
    return current
